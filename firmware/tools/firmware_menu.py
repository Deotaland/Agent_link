"""Generate mode-specific Kconfig menus from supported profile/board bindings."""
import json


def profile_symbol(name):
    return "CONFIG_AGENT_LINK_PROFILE_" + name.upper().replace("-", "_")


def factory_symbol(board):
    return "CONFIG_AGENT_LINK_FACTORY_BOARD_" + board.upper().replace("-", "_")


def factory_boards(profiles):
    boards = {}
    for name, profile in profiles.items():
        if not profile.get("factory"):
            continue
        board = profile["board"]
        if board in boards:
            other = profiles[boards[board]]
            if any(other[key] != profile[key] for key in ("target", "model", "layout")):
                raise ValueError("Factory board revisions need distinct board identities")
            # A network-capable factory uses the board's WiFi combination when
            # several application profiles share the same hardware binding.
            if other["backend"] == "WIFI" or profile["backend"] != "WIFI":
                continue
        boards[board] = name
    return boards


def application_selection(profiles, values, previous=None):
    selected = [name for name in profiles if values.get(profile_symbol(name)) == "y"]
    if len(selected) > 1:
        raise ValueError("Multiple firmware profiles selected; select exactly one")
    if selected:
        return selected[0]
    saved = values.get("CONFIG_AGENT_LINK_SAVED_APPLICATION_PROFILE", "").strip('"')
    return next((name for name in (saved, previous) if name in profiles), None)


def selected_factory(profiles, values):
    boards = factory_boards(profiles)
    known = {factory_symbol(board) for board in boards}
    if any(key.startswith("CONFIG_AGENT_LINK_FACTORY_BOARD_") and value == "y" and key not in known
           for key, value in values.items()):
        raise ValueError("Unsupported Factory board; select a registered board in Menuconfig")
    selected = [board for board in boards if values.get(factory_symbol(board)) == "y"]
    if len(selected) > 1:
        raise ValueError("Multiple Factory boards selected; select exactly one")
    if selected:
        return boards[selected[0]]
    # Migrate an older Factory configuration which had no separate board choice.
    app = application_selection(profiles, values)
    if app and profiles[app].get("factory"):
        return boards[profiles[app]["board"]]
    target = values.get("CONFIG_IDF_TARGET", "").strip('"')
    matches = [name for name in boards.values() if profiles[name]["target"] == target]
    if matches:
        return matches[0]
    raise ValueError("No supported Factory board for the selected chip")


def factory_kconfig(profiles, root):
    boards = factory_boards(profiles)
    chips = sorted({profiles[name]["target"] for name in boards.values()})
    chip_condition = " || ".join("IDF_TARGET_" + chip.upper() for chip in chips) or "n"
    managed = [f'AGENT_LINK_FIRMWARE_PROFILE = "{name}"' for name, p in profiles.items()
               if p["layout_info"]["mode"] == "managed"]
    result = ("# Generated by build_firmware.py --generate-kconfig; do not edit.\n"
              "config AGENT_LINK_CHIP_FACTORY_AVAILABLE\n    bool\n    default y if " + chip_condition + "\n\n"
              "config AGENT_LINK_BOARD_FACTORY_AVAILABLE\n    bool\n    default y if " + (" || ".join(managed) or "n") + "\n\n"
              "config AGENT_LINK_MANAGED_APPS\n    bool\n    default AGENT_LINK_BOARD_FACTORY_AVAILABLE\n\n"
              "choice AGENT_LINK_FACTORY_BOARD_SELECTION\n    prompt \"Factory board\"\n"
              "    depends on AGENT_LINK_BUILD_FACTORY && AGENT_LINK_CHIP_FACTORY_AVAILABLE\n"
              "    help\n        Only hardware with a registered board-bound Factory is listed.\n\n")
    for board, name in boards.items():
        profile = profiles[name]
        catalog = json.loads((root / "boards" / board / "config.json").read_text(encoding="utf-8"))
        entry = next(item for item in catalog["boards"] if item["board_type"] == profile["board_type"])
        label = entry["product"]
        result += (f"    config {factory_symbol(board).removeprefix('CONFIG_')}\n"
                   f"        bool {json.dumps(label)}\n        depends on IDF_TARGET_{profile['target'].upper()}\n\n")
    result += "endchoice\n"
    by_type = {}
    for name, profile in profiles.items():
        by_type.setdefault(profile["board_type"], []).append(f'AGENT_LINK_FIRMWARE_PROFILE = "{name}"')
    for board_type, conditions in by_type.items():
        if len(conditions) > 1:
            result += f"\nconfig BOARD_TYPE_{board_type}\n    bool\n    default y if " + " || ".join(conditions) + "\n"
    return result


def profiles_kconfig(profiles):
    result = ("# Generated by build_firmware.py --generate-kconfig; do not edit.\n"
              "config AGENT_LINK_SAVED_APPLICATION_PROFILE\n    string\n"
              "orsource \"../build/generated/Kconfig.application_selection\"\n\n"
              "choice AGENT_LINK_FIRMWARE_SELECTION\n    prompt \"Application firmware profile\"\n"
              "    depends on AGENT_LINK_BUILD_APPLICATION\n")
    for name in profiles:
        result += (f"    default {profile_symbol(name).removeprefix('CONFIG_')} if "
                   f'AGENT_LINK_SAVED_APPLICATION_PROFILE = "{name}"\n')
    for chip, name in (("esp32s3", "rorolee-ble"), ("esp32c3", "ai-passport-ble"), ("esp32s31", "paper-s31-wifi")):
        if name in profiles:
            result += f"    default {profile_symbol(name).removeprefix('CONFIG_')} if IDF_TARGET_{chip.upper()}\n"
    result += "    help\n        Select an application for the active chip. Factory has a separate board selector.\n\n"
    for name, profile in profiles.items():
        result += (f"    config {profile_symbol(name).removeprefix('CONFIG_')}\n"
                   f"        bool {json.dumps(name + ' (' + profile['backend'] + ')')}\n"
                   f"        depends on IDF_TARGET_{profile['target'].upper()}\n\n")
    result += "endchoice\n\nconfig AGENT_LINK_FIRMWARE_PROFILE\n    string\n"
    for board, name in factory_boards(profiles).items():
        result += f'    default "{name}" if AGENT_LINK_BUILD_FACTORY && {factory_symbol(board).removeprefix("CONFIG_")}\n'
    for name in profiles:
        result += f'    default "{name}" if AGENT_LINK_BUILD_APPLICATION && {profile_symbol(name).removeprefix("CONFIG_")}\n'
    return result


def write_application_cache(path, name):
    path.parent.mkdir(parents=True, exist_ok=True)
    value = ('# Last saved Application selection; generated, not a build target.\n'
             'config AGENT_LINK_SAVED_APPLICATION_PROFILE\n'
             f'    default {json.dumps(name or "")}\n')
    if not path.exists() or path.read_text(encoding="utf-8") != value:
        path.write_text(value, encoding="utf-8", newline="\n")
