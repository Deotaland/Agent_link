"""Derive the C3's flash-only 14 px raster font from the shared CJK image.

Run from the repository root with Pillow and fontTools installed. The generated
four-bit glyphs use the same renderer as Montserrat, with no runtime TTF cache.
"""
import argparse
import io
from pathlib import Path
import struct
import zlib

from PIL import Image, ImageFont
from fontTools.ttLib import TTFont


def build(source):
    image = source.read_bytes()
    magic, version, length, crc, reserved = struct.unpack('<8sIII12s', image[:32])
    if (magic != b'AGLKTTF1' or version != 1 or length != len(image) - 32 or
            reserved != bytes(12) or zlib.crc32(image[32:]) & 0xffffffff != crc):
        raise ValueError('Invalid shared CJK font image')
    raw = image[32:]
    with TTFont(io.BytesIO(raw)) as ttf:
        codepoints = sorted(cp for cp in ttf.getBestCmap() if 32 <= cp <= 0xffff)
    assert codepoints[:95] == list(range(32, 127))
    font = ImageFont.truetype(io.BytesIO(raw), 14)
    bitmap, glyphs = bytearray(), [(0, 0, 0, 0, 0, 0)]
    for cp in codepoints:
        mask, bearing = font.getmask2(chr(cp), mode='L', anchor='ls')
        pixels = Image.frombytes('L', mask.size, bytes(mask))
        ink = pixels.getbbox()
        advance = round(font.getlength(chr(cp)) * 16) if cp < 127 else 14 * 16
        if not ink:
            glyphs.append((len(bitmap), advance, 0, 0, 0, 0))
            continue
        pixels = pixels.crop(ink)
        # Keep the complete outline of unusually tall/wide symbols inside the
        # same line box. Common Hanzi retain their original rasterization.
        scale = min(1, 14 / pixels.width, 18 / pixels.height)
        if scale < 1:
            pixels = pixels.resize((max(1, round(pixels.width * scale)),
                                    max(1, round(pixels.height * scale))), Image.Resampling.LANCZOS)
        width, height = pixels.size
        x = max(0, (round(advance / 16) - width) // 2)
        y = max(0, min(18 - height, 15 + bearing[1] + ink[1]))
        glyphs.append((len(bitmap), advance, width, height, x, 15 - height - y))
        values = [(value * 15 + 127) // 255 for value in pixels.tobytes()]
        for i in range(0, len(values), 2):
            bitmap.append((values[i] << 4) | (values[i + 1] if i + 1 < len(values) else 0))
    sparse = [cp - 127 for cp in codepoints[95:]]
    lines = ['// Generated by fonts/make_raster_cjk.py from cjk_font.bin (Noto Sans SC).',
             '// SIL Open Font License: fonts/OFL.txt. Do not edit glyph data by hand.',
             '#include "raster_font.h"', '', 'static const uint8_t bitmap[] = {']
    for i in range(0, len(bitmap), 24):
        lines.append('    ' + ','.join(f'0x{v:02x}' for v in bitmap[i:i + 24]) + ',')
    lines += ['};', '', 'static const raster_glyph_t glyphs[] = {']
    lines += ['    {' + ','.join(map(str, glyph)) + '},' for glyph in glyphs]
    lines += ['};', '', 'static const uint16_t sparse[] = {']
    for i in range(0, len(sparse), 16):
        lines.append('    ' + ','.join(map(str, sparse[i:i + 16])) + ',')
    lines += ['};', '', 'const raster_font_t raster_cjk_14 = {',
              '    bitmap, glyphs, sparse, 0, 0, 0,',
              f'    {len(sparse)}, {len(glyphs)}, 0, 18, 3, 127', '};', '']
    return '\n'.join(lines), len(codepoints), len(bitmap)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    common = Path(__file__).resolve().parent.parent
    parser.add_argument('--source', type=Path, default=common / 'fonts/cjk_font.bin')
    parser.add_argument('--output', type=Path, default=common / 'raster_cjk_14.c')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, count, size = build(args.source)
    if args.check:
        if args.output.read_text(encoding='utf-8') != text:
            raise SystemExit('Raster font is stale; regenerate with make_raster_cjk.py')
    else:
        args.output.write_text(text, encoding='utf-8', newline='\n')
    print(f'Raster CJK: {count} characters, {size} bitmap bytes, 14 px, flash-only')
